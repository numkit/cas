#!/usr/bin/env python3
"""Vendor the numkit-cas core into the Numkit tree (or a dry-run dir).

Copies the whitelist (public headers + library sources, NOTHING else:
no tests, no apps, no corpora, no notes) into the destination and
writes a self-contained CMakeLists.txt there that builds the static
library `numkit_cas`. The destination then hooks into Numkit via

    add_subdirectory(<dest>)

Run from the numkit-cas repository root:

    python tools/vendor_sync.py --dest <path> [--dry-run]

The file list is explicit on purpose: the vendored layout mirrors
include/numkit/cas/** and src/** so the Numkit tree needs no include
path changes, and anything NOT listed here never leaks out.
"""

import argparse
import pathlib
import shutil
import sys

HEADERS = [
    "include/numkit/cas/num/bigint.hpp",
    "include/numkit/cas/num/rational.hpp",
    "include/numkit/cas/core/budget.hpp",
    "include/numkit/cas/core/expr.hpp",
    "include/numkit/cas/core/parser.hpp",
    "include/numkit/cas/core/series.hpp",
    "include/numkit/cas/core/simplify.hpp",
    "include/numkit/cas/core/symsolve.hpp",
    "include/numkit/cas/integrate/ratint.hpp",
    "include/numkit/cas/integrate/verify.hpp",
    "include/numkit/cas/linalg/symmatrix.hpp",
    "include/numkit/cas/ode/dsolve.hpp",
    "include/numkit/cas/poly/upoly.hpp",
    "include/numkit/cas/poly/sturm.hpp",
    "include/numkit/cas/poly/algebraic.hpp",
    "include/numkit/cas/poly/modcpoly.hpp",
    "include/numkit/cas/poly/fppoly.hpp",
    "include/numkit/cas/poly/zassenhaus.hpp",
    "include/numkit/cas/poly/solve.hpp",
    "include/numkit/cas/rubi/rules.hpp",
    "include/numkit/cas/transform/laplace.hpp",
]

SOURCES = [
    "src/num/bigint.cpp",
    "src/num/rational.cpp",
    "src/core/expr.cpp",
    "src/core/diff.cpp",
    "src/core/parser.cpp",
    "src/core/series.cpp",
    "src/core/simplify.cpp",
    "src/core/symsolve.cpp",
    "src/integrate/ratint.cpp",
    "src/integrate/verify.cpp",
    "src/linalg/symmatrix.cpp",
    "src/ode/dsolve.cpp",
    "src/poly/upoly.cpp",
    "src/poly/sturm.cpp",
    "src/poly/algebraic.cpp",
    "src/poly/modcpoly.cpp",
    "src/poly/fppoly.cpp",
    "src/poly/zassenhaus.cpp",
    "src/poly/solve.cpp",
    "src/rubi/rules.cpp",
    "src/rubi/rubi_tables_1111.inc",
    "src/transform/laplace.cpp",
]

CMAKE_TEMPLATE = """\
# AUTO-GENERATED by numkit-cas tools/vendor_sync.py - do not edit.
add_library(numkit_cas STATIC
{sources}
)
add_library(numkit::cas ALIAS numkit_cas)
target_include_directories(numkit_cas PUBLIC ${{CMAKE_CURRENT_SOURCE_DIR}}/include)
target_compile_features(numkit_cas PUBLIC cxx_std_17)
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dest", required=True, help="destination directory")
    ap.add_argument("--dry-run", action="store_true",
                    help="list the copies, write nothing")
    args = ap.parse_args()

    root = pathlib.Path(__file__).resolve().parent.parent
    dest = pathlib.Path(args.dest)
    files = HEADERS + SOURCES
    for rel in files:
        src = root / rel
        if not src.is_file():
            print(f"MISSING: {rel}", file=sys.stderr)
            return 1
        out = dest / rel
        if args.dry_run:
            print(f"would copy {rel} -> {out}")
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, out)
        print(f"copied {rel}")
    if args.dry_run:
        print("dry run: nothing written")
        return 0
    dest.joinpath("CMakeLists.txt").write_text(
        CMAKE_TEMPLATE.format(
            sources="\n".join(f"    {s}" for s in SOURCES)) + "\n",
        encoding="utf-8", newline="\n")
    print(f"wrote {dest / 'CMakeLists.txt'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
