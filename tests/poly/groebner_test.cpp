TEST(GroebnerTest, LexAndGrevLexReducedBasisFixedVectors)
{
    Ctx c;
    const Expr x = c.symbol("x");
    const Expr y = c.symbol("y");
    const Expr z = c.symbol("z");

    // 1. Twisted cubic in Q[x, y, z] (x > y > z):
    //    I = <x - z^3, y - z^2>
    //    Lex basis:     {y - z^2, x - z^3}
    //    GrevLex basis: {x - y*z, y^2 - x*z, z^2 - y}
    {
        const std::vector<Expr> gens = {
            parseExpr(c, "x - z^3"),
            parseExpr(c, "y - z^2")};
        const GroebnerResult gbLex =
            groebnerBasis(c, gens, {x, y, z}, MonomialOrder::Lex);
        ASSERT_TRUE(gbLex.proved()) << gbLex.reason;
        ASSERT_EQ(gbLex.basis.size(), 2u);
        EXPECT_TRUE(
            c.isZero(c.simplify(c.add({gbLex.basis[0], c.neg(parseExpr(c, "y - z^2"))}))));
        EXPECT_TRUE(
            c.isZero(c.simplify(c.add({gbLex.basis[1], c.neg(parseExpr(c, "x - z^3"))}))));

        const GroebnerResult gbGrev =
            groebnerBasis(c, gens, {x, y, z}, MonomialOrder::GrevLex);
        ASSERT_TRUE(gbGrev.proved()) << gbGrev.reason;
        ASSERT_EQ(gbGrev.basis.size(), 3u);
        // Every generator of Lex basis reduces to 0 modulo GrevLex basis and vice versa
        for (const Expr &g : gbLex.basis) {
            EXPECT_TRUE(c.isZero(
                polyReduceMulti(c, g, gbGrev.basis, {x, y, z},
                                MonomialOrder::GrevLex)));
        }
        for (const Expr &g : gbGrev.basis) {
            EXPECT_TRUE(c.isZero(
                polyReduceMulti(c, g, gbLex.basis, {x, y, z},
                                MonomialOrder::Lex)));
        }
    }

    // 2. Circle and hyperbola intersection in Q[x, y] (x > y):
    //    <x^2 + y^2 - 5, x*y - 2>
    //    Lex basis: {y^4 - 5*y^2 + 4, x + 1/2*y^3 - 5/2*y}
    {
        const std::vector<Expr> gens = {
            parseExpr(c, "x^2 + y^2 - 5"),
            parseExpr(c, "x*y - 2")};
        const GroebnerResult gb =
            groebnerBasis(c, gens, {x, y}, MonomialOrder::Lex);
        ASSERT_TRUE(gb.proved()) << gb.reason;
        ASSERT_EQ(gb.basis.size(), 2u);
        EXPECT_TRUE(c.isZero(c.simplify(
            c.add({gb.basis[0], c.neg(parseExpr(c, "y^4 - 5*y^2 + 4"))}))));
        EXPECT_TRUE(c.isZero(c.simplify(
            c.add({gb.basis[1], c.neg(parseExpr(c, "x + 1/2*y^3 - 5/2*y"))}))));
    }

    // 3. Inconsistent system -> unit ideal {1}
    {
        const std::vector<Expr> gens = {
            parseExpr(c, "x + y - 1"),
            parseExpr(c, "x^2 - y^2 - 3"),
            parseExpr(c, "x - y - 1")};
        const GroebnerResult gb =
            groebnerBasis(c, gens, {x, y}, MonomialOrder::Lex);
        ASSERT_TRUE(gb.proved()) << gb.reason;
        ASSERT_EQ(gb.basis.size(), 1u);
        EXPECT_EQ(gb.basis[0], c.one());
    }

    // 4. Multivariate normal-form reduction `polyReduceMulti`
    {
        const std::vector<Expr> gens = {
            parseExpr(c, "x^2 + y^2 - 1"),
            parseExpr(c, "x - y")};
        const GroebnerResult gb =
            groebnerBasis(c, gens, {x, y}, MonomialOrder::Lex);
        ASSERT_TRUE(gb.proved());
        // x^3 + y^3 mod <y^2 - 1/2, x - y> == 2*y^3 == y
        const Expr rem = polyReduceMulti(
            c, parseExpr(c, "x^3 + y^3"), gb.basis, {x, y}, MonomialOrder::Lex);
        EXPECT_EQ(c.toString(rem), "y");
    }
}

// ============================================================================
// Layer 2: Property Tests (Uniqueness of Reduced Basis & Ideal Membership)
// ============================================================================

TEST(GroebnerTest, PropertyIdealMembershipAndCanonicalUniqueness)
{
    Ctx c;
    const Expr x = c.symbol("x");
    const Expr y = c.symbol("y");
    const Expr z = c.symbol("z");
    const std::vector<Expr> vars = {x, y, z};

    std::mt19937_64 rng(0x6B0E84E2ULL);
    std::uniform_int_distribution<int> rootDist(-3, 3);
    std::uniform_int_distribution<int> mixDist(1, 3);

    for (int iter = 0; iter < 30; ++iter) {
        const int x0 = rootDist(rng);
        const int y0 = rootDist(rng);
        const int z0 = rootDist(rng);

        // Ideal of point (x0, y0, z0) generated by scrambled nonlinear combinations
        const Expr f1 = c.add({x, c.number(-x0)});
        const Expr f2 = c.add({y, c.number(-y0)});
        const Expr f3 = c.add({z, c.number(-z0)});

        const int a = mixDist(rng);
        const int b = mixDist(rng);
        const Expr g1 = c.expand(c.add({f1, c.mul({c.number(a), f2, f3})}));
        const Expr g2 = c.expand(c.add({f2, c.mul({c.number(b), c.pow(f3, c.number(2))})}));
        const Expr g3 = c.expand(c.add({f3, c.mul({f1, f2}), c.neg(c.mul({f1, f2}))}));

        const GroebnerResult gb =
            groebnerBasis(c, {g1, g2, g3}, vars, MonomialOrder::Lex);
        ASSERT_TRUE(gb.proved()) << gb.reason;
        ASSERT_EQ(gb.basis.size(), 3u);
        // Unique reduced monic Groebner basis of the maximal ideal <x-x0, y-y0, z-z0>
        EXPECT_TRUE(c.isZero(c.simplify(c.add({gb.basis[0], c.neg(f3)}))));
        EXPECT_TRUE(c.isZero(c.simplify(c.add({gb.basis[1], c.neg(f2)}))));
        EXPECT_TRUE(c.isZero(c.simplify(c.add({gb.basis[2], c.neg(f1)}))));

        // Random combination h = (x + y)*g1 + (z - 1)*g2 must reduce to 0 modulo gb.basis
        const Expr h = c.expand(c.add(
            {c.mul({c.add({x, y}), g1}),
             c.mul({c.add({z, c.number(-1)}), g2})}));
        const Expr rem =
            polyReduceMulti(c, h, gb.basis, vars, MonomialOrder::Lex);
        EXPECT_TRUE(c.isZero(rem));
    }
}

